#1- Aritmeticos
#2- Relacionales
a= 20
b= 10
#Mayor que >
resultado = a > b
print("El resultado de a > b es: ", resultado)
#Menor que <
resultado = a < b   
print("El resultado de a < b es: ", resultado)
#Diferente de !=
resultado = a != b
print("El resultado de a != b es: ", resultado)
#Igual que ==
resultado = a == b
print("El resultado de a == b es: ", resultado)
#Mayor o igual que >=
resultado = a >= b
print("El resultado de a >= b es: ", resultado)
#Menor o igual que <=
resultado = a <= b
print("El resultado de a <= b es: ", resultado)